/**
 * Write static/_redirects: the old joblist.today company pages (/<slug>)
 * moved to /company/<rkey> when the app took over the root domain,
 * and its sitemap to /sitemap.xml; /settings became /menu.
 *
 *   node scripts/legacy-redirects.js [<companies-dir>]
 *
 * The old companies no longer change, so the file is generated once and committed.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { readLegacyCompanies, toRedirects } from './lib/legacy.js';

const [dir = '../workers/.db-github-data/companies'] = process.argv.slice(2);
const reserved = readdirSync('src/routes').filter((name) => !name.startsWith('+') && !name.startsWith('['));
const lines = toRedirects(readLegacyCompanies(dir), reserved);

writeFileSync(
	'static/_redirects',
	[
		'# Old joblist.today pages, generated by scripts/legacy-redirects.js',
		'/sitemap-index.xml /sitemap.xml 301',
		'/settings /menu 301',
		...lines,
		''
	].join('\n')
);
console.log(`${lines.length} redirects written to static/_redirects`);
